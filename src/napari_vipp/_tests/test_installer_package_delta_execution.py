def _save(tx):
    tx.journal.write_text(json.dumps(tx.document), encoding="utf-8")


def _no_host(monkeypatch):
    def forbidden(*args, **kwargs):
        pytest.fail("Disposable executor test reached a host process boundary")

    monkeypatch.setattr(legacy, "_windows_processes", forbidden)
    monkeypatch.setattr(rt, "_process", forbidden)
    return forbidden


def _offline(tx):
    os.rename(tx.old.environment_root, tx.plan.offline)
    tx.document["phase"] = "exchanging"


def _accepted_guard(tx):
    # The production executor removes empty touched old metadata directories
    # after exchange and before adoption. A direct exchange fixture must do so
    # too: an empty old .dist-info is not a healthy installed distribution.
    files.remove_empty_payload_directories(tx.old.environment_root, tx.old_files)
    guard = tx.site / legacy.GUARD_NAME
    guard.write_bytes(legacy.GUARD_BYTES)
    return guard


