def test_preexchange_abort_kill_after_canonical_restore_resumes_same_as_is_abort(
    transaction, monkeypatch
):
    tx = transaction
    forbidden = _no_host(monkeypatch)
    monkeypatch.setattr(execution, "_exclude", forbidden)
    monkeypatch.setattr(files, "exchange", forbidden)
    monkeypatch.setattr(files, "restore", forbidden)
    os.rename(tx.old.environment_root, tx.plan.offline)
    cache = (
        tx.plan.offline
        / "Lib/site-packages/napari_vipp/__pycache__/__init__.cpython-312.pyc"
    )
    cache.write_bytes(b"old cache regenerated before package mutation")
    tx.document["phase"] = "excluding"
    _save(tx)
    before = fixtures.snapshot(tx.plan.offline)
    staged = fixtures.snapshot(tx.payload)
    journal = tx.journal.read_bytes()
    real_cleanup = files.cleanup

    class SimulatedPowerLoss(BaseException):
        pass

    def interrupted_cleanup(*args):
        assert tx.old.environment_root.is_dir()
        assert not tx.plan.offline.exists()
        assert json.loads(tx.journal.read_bytes())["phase"] == "excluding"
        raise SimulatedPowerLoss

    monkeypatch.setattr(files, "cleanup", interrupted_cleanup)
    with pytest.raises(SimulatedPowerLoss):
        execution.recover_if_delta(tx.engine, tx.journal, tx.old.managed_root)
    assert fixtures.snapshot(tx.old.environment_root) == before
    assert fixtures.snapshot(tx.payload) == staged
    assert tx.journal.read_bytes() == journal
    monkeypatch.setattr(files, "cleanup", real_cleanup)
    report = execution.recover_if_delta(tx.engine, tx.journal, tx.old.managed_root)
    assert report.completed, report.errors
    assert fixtures.snapshot(tx.old.environment_root) == before
    assert inspect_ownership(tx.old.managed_root).record == tx.old
    assert not tx.journal.exists()
    assert not tx.payload.exists()


